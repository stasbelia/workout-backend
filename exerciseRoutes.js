const express = require('express');

const { parseBody } = require('./exerciseInput');
const EXERCISE_COLUMNS = 'id, name, notes, position, created_at AS "createdAt", revision';
const WORKOUT_COLUMNS = 'id, title, workout_date::text AS date, notes, created_at AS "createdAt", completed_at AS "completedAt", revision';
const validId = (id) => typeof id === 'string' && /^[1-9]\d{0,9}$/.test(id) && Number(id) <= 2147483647;
const SET_COLUMNS = 'position, reps, weight_kg::float8 AS "weightKg"';

// Mounted under the workout router, after JWT, request limits and its JSON parser.
module.exports = function createExerciseRouter({ pool }) {
  const router = express.Router({ mergeParams: true });
  router.use(async (req, res, next) => {
    if (!validId(req.params.workoutId)) return res.status(400).json({ error: 'Некоректний номер тренування.' });
    try {
      const user = await pool.query('SELECT id FROM users WHERE id = $1', [req.user.id]);
      if (!user.rows.length) return res.status(401).json({ error: 'Увійдіть повторно.' });
      return next();
    } catch (error) { return next(error); }
  });

  router.get('/', async (req, res, next) => {
    if (Object.keys(req.query).length) return res.status(400).json({ error: 'Некоректний запит тренування.' });
    try {
      const result = await pool.query(
        `SELECT ${WORKOUT_COLUMNS} FROM workouts WHERE id = $1 AND user_id = $2`,
        [Number(req.params.workoutId), req.user.id]
      );
      if (!result.rows.length) return res.status(404).json({ error: 'Тренування не знайдено.' });
      const exercises = await pool.query(
        `SELECT ${EXERCISE_COLUMNS} FROM workout_exercises
         WHERE workout_id = $1 AND EXISTS (SELECT 1 FROM workouts WHERE id = $1 AND user_id = $2)
         ORDER BY position LIMIT 100`,
        [Number(req.params.workoutId), req.user.id]
      );
      const sets = await pool.query(
        `SELECT s.exercise_id AS "exerciseId", s.position, s.reps, s.weight_kg::float8 AS "weightKg"
         FROM exercise_sets s JOIN workout_exercises e ON e.id = s.exercise_id JOIN workouts w ON w.id = e.workout_id
         WHERE w.id = $1 AND w.user_id = $2 ORDER BY e.position, s.position LIMIT 3000`,
        [Number(req.params.workoutId), req.user.id]
      );
      return res.json({ workout: result.rows[0], exercises: exercises.rows.map((exercise) => ({
        ...exercise,
        sets: sets.rows.filter((set) => set.exerciseId === exercise.id).map(({ exerciseId, ...set }) => set),
      })) });
    } catch (error) { return next(error); }
  });

  // The desired state makes retries safe after a lost response; timestamps are
  // generated by PostgreSQL and preserved when completing an already done record.
  router.patch('/completion', async (req, res, next) => {
    const body = req.body;
    const { isDate } = require('./workoutInput');
    if (Object.keys(req.query).length || !body || Array.isArray(body) ||
        Object.keys(body).length !== 2 || typeof body.completed !== 'boolean' || !isDate(body.today)) {
      return res.status(400).json({ error: 'Некоректний стан або дата тренування.' });
    }
    let client, transaction = false;
    try {
      client = await pool.connect();
      await client.query('BEGIN'); transaction = true;
      const workout = (await client.query(
        `SELECT ${WORKOUT_COLUMNS} FROM workouts WHERE id=$1 AND user_id=$2 FOR UPDATE`,
        [Number(req.params.workoutId), req.user.id]
      )).rows[0];
      if (!workout) {
        await client.query('ROLLBACK'); transaction = false;
        return res.status(404).json({ error: 'Тренування не знайдено.' });
      }
      if (body.completed && !workout.completedAt) {
        if (workout.date > body.today) {
          await client.query('ROLLBACK'); transaction = false;
          return res.status(409).json({ error: 'Майбутнє тренування ще не можна завершити. Перевірте його дату.' });
        }
        const hasSets = (await client.query(
          `SELECT 1 FROM workout_exercises e JOIN exercise_sets s ON s.exercise_id=e.id
           WHERE e.workout_id=$1 LIMIT 1`, [workout.id]
        )).rows.length > 0;
        if (!hasSets) {
          await client.query('ROLLBACK'); transaction = false;
          return res.status(409).json({ error: 'Спочатку додайте вправу з підходами.' });
        }
      }
      const result = await client.query(
        `UPDATE workouts SET revision=revision + CASE WHEN (completed_at IS NOT NULL) IS DISTINCT FROM $3::boolean THEN 1 ELSE 0 END,
           completed_at=CASE WHEN $3::boolean THEN COALESCE(completed_at, now()) ELSE NULL END
         WHERE id=$1 AND user_id=$2 RETURNING ${WORKOUT_COLUMNS}`,
        [workout.id, req.user.id, body.completed]
      );
      await client.query('COMMIT'); transaction = false;
      return res.json({ workout: result.rows[0] });
    } catch (error) {
      if (client && transaction) await client.query('ROLLBACK').catch(() => {});
      return next(error);
    } finally { client?.release(); }
  });

  router.post('/exercises', async (req, res, next) => {
    const body = parseBody(req.body);
    if (!body || Object.keys(req.query).length) {
      return res.status(400).json({ error: 'Перевірте назву (до 100 символів), нотатку (до 500) та підходи: повторення 1–1000, вага 0–1000 кг, до двох знаків після коми.' });
    }
    let client;
    let transaction = false;
    try {
      client = await pool.connect();
      await client.query('BEGIN'); transaction = true;
      const owned = await client.query('SELECT id FROM workouts WHERE id = $1 AND user_id = $2 FOR UPDATE', [Number(req.params.workoutId), req.user.id]);
      if (!owned.rows.length) {
        await client.query('ROLLBACK'); transaction = false;
        return res.status(404).json({ error: 'Тренування не знайдено.' });
      }
      const existing = await client.query(
        `SELECT ${EXERCISE_COLUMNS} FROM workout_exercises WHERE workout_id = $1 AND client_request_id = $2::uuid`,
        [Number(req.params.workoutId), body.clientRequestId]
      );
      if (existing.rows.length) {
        const exercise = existing.rows[0];
        const sets = await client.query(`SELECT ${SET_COLUMNS} FROM exercise_sets WHERE exercise_id = $1 ORDER BY position`, [exercise.id]);
        await client.query('COMMIT'); transaction = false;
        if (exercise.name !== body.name || exercise.notes !== body.notes ||
            JSON.stringify(sets.rows.map(({ reps, weightKg }) => ({ reps, weightKg }))) !== JSON.stringify(body.sets)) {
          return res.status(409).json({ error: 'Цей запит уже зберіг іншу вправу. Перевірте список вправ.' });
        }
        return res.json({ exercise: { ...exercise, sets: sets.rows } });
      }
      const { rows } = await client.query('SELECT COALESCE(MAX(position), 0)::int AS last FROM workout_exercises WHERE workout_id = $1', [Number(req.params.workoutId)]);
      if (rows[0].last >= 100) {
        await client.query('ROLLBACK'); transaction = false;
        return res.status(409).json({ error: 'У тренуванні вже є 100 вправ. Створіть інше тренування.' });
      }
      const inserted = await client.query(
        `INSERT INTO workout_exercises(workout_id, client_request_id, name, notes, position)
         VALUES ($1, $2::uuid, $3, $4, $5) RETURNING ${EXERCISE_COLUMNS}`,
        [Number(req.params.workoutId), body.clientRequestId, body.name, body.notes, rows[0].last + 1]
      );
      const sets = await client.query(
        `INSERT INTO exercise_sets(exercise_id, position, reps, weight_kg)
         SELECT $1, ord::int, (item->>'reps')::int, (item->>'weightKg')::numeric
         FROM jsonb_array_elements($2::jsonb) WITH ORDINALITY AS entries(item, ord)
         RETURNING ${SET_COLUMNS}`,
        [inserted.rows[0].id, JSON.stringify(body.sets)]
      );
      await client.query('UPDATE workouts SET revision=revision+1 WHERE id=$1 AND user_id=$2', [Number(req.params.workoutId), req.user.id]);
      await client.query('COMMIT'); transaction = false;
      return res.status(201).json({ exercise: { ...inserted.rows[0], sets: sets.rows.sort((a, b) => a.position - b.position) } });
    } catch (error) {
      if (client && transaction) await client.query('ROLLBACK').catch(() => {});
      return next(error);
    } finally { client?.release(); }
  });
  require('./workoutEditRoutes')(router, { pool, WORKOUT_COLUMNS, EXERCISE_COLUMNS, SET_COLUMNS });
  return router;
};
